const fs = require('fs');
const { compile } = require('json-schema-to-typescript');
const Ajv = require('ajv/dist/2020').default;
const standalone = require('ajv/dist/standalone').default;
const schema = JSON.parse(fs.readFileSync('../../schema/protocol.schema.json', 'utf8'));
(async () => {
  fs.writeFileSync('src/protocol.generated.ts', await compile(schema, 'Protocol', { unreachableDefinitions: true }));
  const ajv = new Ajv({ code: { source: true }, strict: false, validateFormats: false });
  const validate = ajv.compile({ $schema: schema.$schema, $defs: schema.$defs, $ref: '#/$defs/LiveSnapshot' });
  const code = standalone(ajv, validate).replace('module.exports = validate20;', 'export const validateSnapshot = validate20;').replace('module.exports.default = validate20;', '');
  fs.writeFileSync('src/validate.generated.ts', '// @ts-nocheck\n// Generated by scripts/generate-protocol.cjs.\n' + code + '\n');
})();
